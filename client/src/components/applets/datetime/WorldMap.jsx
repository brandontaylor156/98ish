const x = (lon) => lon + 180
const y = (lat) => TOP - lat
const points = (shape) => shape.map(([lon, lat]) => `${x(lon).toFixed(1)},${y(lat).toFixed(1)}`).join(" ")

// lon/lat for a click on the map
export const lonLatAt = (svg, clientX, clientY) => {
  const r = svg.getBoundingClientRect()
  return [((clientX - r.left) / r.width) * MAP_W - 180, TOP - ((clientY - r.top) / r.height) * MAP_H]
}

const WorldMap = ({ offsetHours, marker, onPick }) => {
  // the zone's band: 15 degrees of longitude per hour, wrapping around the date line
  const center = offsetHours * 15
  const bands = [-360, 0, 360].map((shift) => center - 7.5 + shift).filter((left) => left + 15 > -180 && left < 180)

  return (
    <svg
      className="dtMap"
      viewBox={`0 0 ${MAP_W} ${MAP_H}`}
      preserveAspectRatio="none"
      role="img"
      aria-label="World map showing the selected time zone"
      onClick={(e) => onPick?.(lonLatAt(e.currentTarget, e.clientX, e.clientY))}
    >
      <rect width={MAP_W} height={MAP_H} fill="#008080" />
      {/* lines of longitude every 15 degrees: one per hour */}
      {Array.from({ length: 23 }, (_, i) => (
        <line key={i} x1={(i + 1) * 15} x2={(i + 1) * 15} y1="0" y2={MAP_H} stroke="#0a9a9a" strokeWidth="0.6" />
      ))}
      {LAND.map((shape, i) => (
        <polygon key={i} points={points(shape)} fill={i === LAND.length - 1 ? "#d8d8d8" : "#7fc77f"} stroke="#205020" strokeWidth="0.6" strokeLinejoin="round" />
      ))}
      {bands.map((left) => (
        <rect key={left} className="dtMapBand" x={x(left)} y="0" width="15" height={MAP_H} fill="#ffff80" fillOpacity="0.45" stroke="#ffff00" strokeWidth="0.8" />
      ))}
      {marker && (
        <g className="dtMapMarker">
          <circle cx={x(marker.lon)} cy={y(marker.lat)} r="3.4" fill="#ff0000" stroke="#fff" strokeWidth="1.2" />
        </g>
      )}
    </svg>
  )
}

export default WorldMap
